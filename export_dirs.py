"""Export steer directions into brosoundml as BF16 hex tables.

    .venv/Scripts/python export_dirs.py ../brosoundml/src/yue2_style_directions.inc \
        density:24 timbre:24 tempo:24

Each <axis>:<layer> is cache/dirs/<axis>_semantic_L<layer>_e-1.f32 (2048
floats, the raw difference of means of the paired contrast), written as
`const char kSemantic_<axis>_L<layer>[] = "...";`, four hex digits per value
(the top 16 bits of the float after round-to-nearest-even): the format
yue2_directions.cpp's decode() reads. The include is generated; edit this
script, not it.
"""
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent


def bf16_hex(v):
    u = np.asarray(v, dtype=np.float32).view(np.uint32).astype(np.uint64)
    r = ((u + 0x7FFF + ((u >> 16) & 1)) >> 16) & 0xFFFF
    return "".join(f"{int(x):04x}" for x in r)


def main():
    out = Path(sys.argv[1])
    lines = ["// Generated by yue2-research/export_dirs.py: semantic steer directions,",
             "// BF16 hex (yue2_directions.cpp). Do not edit.", ""]
    for spec in sys.argv[2:]:
        axis, layer = spec.split(":")
        src = ROOT / f"cache/dirs/{axis}_semantic_L{layer}_e-1.f32"
        v = np.fromfile(src, dtype=np.float32)
        assert v.size == 2048, f"{src}: {v.size} floats"
        h = bf16_hex(v)
        lines.append(f"// {src.name}: |d| = {float(np.linalg.norm(v)):.3f}")
        lines.append(f"const char kSemantic_{axis}_L{layer}[] =")
        for i in range(0, len(h), 128):
            lines.append(f'    "{h[i:i + 128]}"' + (";" if i + 128 >= len(h) else ""))
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
